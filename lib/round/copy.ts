export const copy: Record<Lang, Record<CopyKey, string>> = { th, en };

export type CopyParams = Record<string, string | number | null | undefined>;

export function format(template: string, params: CopyParams = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name];
    return value === undefined || value === null ? match : String(value);
  });
}

export function t(lang: Lang, key: CopyKey, params?: CopyParams): string {
  const table = copy[lang] ?? copy.th;
  return format(table[key] ?? copy.th[key] ?? key, params);
}

export function hasKey(key: string): key is CopyKey {
  return Object.prototype.hasOwnProperty.call(th, key);
}

/** Error copy for a code, falling back to the category (never shows raw codes). */
export function errorCopy(
  lang: Lang,
  error: { code: string; category: string; field?: string | null; retry_after?: number | null; details?: Record<string, unknown> },
  params: CopyParams = {},
): string {
  if (error.code === "invalid_field" && error.details && error.details.rule === "personal_data") {
    return t(lang, "error.invalid_field.personal_data");
  }
  const key = `error.${error.code}`;
  const merged: CopyParams = {
    field: error.field ?? "",
    minutes: error.retry_after ? Math.max(1, Math.ceil(error.retry_after / 60)) : 1,
    ...(error.details as CopyParams | undefined),
    ...params,
  };
  if (hasKey(key)) return t(lang, key, merged);
  const fallback = `error.${error.category}`;
  return hasKey(fallback) ? t(lang, fallback, merged) : t(lang, "error.unavailable");
}
